export const codeLanguages = Object.keys(languageLabels);

export function normalizeCodeLanguage(language: string): string {
    const name = language.trim().toLowerCase();
    return languageAliases[name] ?? name;
}

export function codeLanguageLabel(language: string): string {
    const name = normalizeCodeLanguage(language);
    return languageLabels[name] ?? language;
}

export function codeLanguageSearchKeywords(language: string): string[] {
    const name = normalizeCodeLanguage(language);
    const aliases = Object.entries(languageAliases)
        .filter(([, canonical]) => canonical === name)
        .map(([alias]) => alias);
    const relatedTerms =
        name === 'jsx'
            ? ['javascript', 'react']
            : name === 'tsx'
              ? ['typescript', 'react']
              : [];
    return [name, ...aliases, ...relatedTerms];
}
